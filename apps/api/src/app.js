import express from 'express';
import helmet from 'helmet';
import cors from 'cors';
import cookieParser from 'cookie-parser';
import { config, corsOrigin } from './config.js';
import { healthRouter } from './routes/health.js';
import { authRouter, meRouter } from './routes/auth.js';
import { casesRouter } from './routes/cases.js';
import { caseEvidenceRouter, evidenceRouter } from './routes/evidence.js';
import { caseDataRouter } from './routes/case-data.js';
import { exportRouter } from './routes/export.js';
import { caseStatementsRouter, statementRouter } from './routes/statements.js';
import { caseTimestampsRouter, timestampRouter } from './routes/timestamps.js';
import { advancedRouter } from './routes/advanced.js';
import { investigationRouter } from './routes/investigation.js';
import { legalRouter } from './routes/legal.js';
import { regionalRouter } from './routes/regional.js';
import { adminRouter, caseSharesRouter, officerRouter, oversightRouter, shareRouter } from './routes/sharing.js';
import { internalRouter } from './routes/internal.js';
import { errorHandler } from './middleware/index.js';

export function createApp() {
  const app = express();
  // Behind Vercel's rewrite + the host's load balancer: trust X-Forwarded-For so rate limits see real client IPs.
  app.set('trust proxy', config.TRUST_PROXY);
  app.use(helmet({ contentSecurityPolicy: { directives: { 'frame-ancestors': ["'none'"] } } }));
  app.use(cors({ origin: corsOrigin, credentials: true }));
  app.use(express.json({ limit: '1mb' }));
  app.use(cookieParser());
  app.use('/api/v1', healthRouter);
  app.use('/api/v1/internal', internalRouter);
  app.use('/api/v1/auth', authRouter);
  app.use('/api/v1/me', meRouter);
  app.use('/api/v1/cases', casesRouter);
  app.use('/api/v1/cases/:id/evidence', caseEvidenceRouter);
  app.use('/api/v1/cases/:id/shares', caseSharesRouter);
  app.use('/api/v1/share', shareRouter);
  app.use('/api/v1/officer', officerRouter);
  app.use('/api/v1/oversight', oversightRouter);
  app.use('/api/v1/admin', adminRouter);
  app.use('/api/v1/legal', legalRouter);
  app.use('/api/v1/cases/:id/regional', regionalRouter);
  app.use('/api/v1/cases/:id/export', exportRouter);
  app.use('/api/v1/cases/:id/statements', caseStatementsRouter);
  app.use('/api/v1/cases/:id/trusted-timestamps', caseTimestampsRouter);
  app.use('/api/v1/trusted-timestamps', timestampRouter);
  app.use('/api/v1/statements', statementRouter);
  app.use('/api/v1/cases/:id', advancedRouter);
  app.use('/api/v1/cases/:id', investigationRouter);
  app.use('/api/v1/cases/:id', caseDataRouter);
  app.use('/api/v1/evidence', evidenceRouter);
  app.use((_req, res) => res.status(404).json({ error: { code: 'NOT_FOUND', message: 'Not found' } }));
  app.use(errorHandler);
  return app;
}
